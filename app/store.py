"""
Per-job isolated storage.

- One job = one UUID directory under DATA_DIR/jobs/<job_id>/ .
- Files are 0600, directories 0700.
- Access requires the per-job file_token (secrets.token_urlsafe, in
  memory only, never in logs). A token for job A cannot read job B.
- Nothing credential-like is ever written to disk. The session value
  lives only in the running browser context's memory and is dropped
  when the context closes.
- TTL: jobs (status + files) expire 30 minutes after creation.
  A sweeper deletes expired job directories. A job's files are
  also deleted immediately if the user calls DELETE /api/jobs/{id}.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import secrets
import shutil
import time
from pathlib import Path

DATA_DIR = Path(os.environ.get("DATA_DIR", Path(__file__).resolve().parent.parent / "data"))
JOBS_DIR = DATA_DIR / "jobs"
TTL_SECONDS = int(os.environ.get("JOB_TTL_SECONDS", "1800"))  # 30 minutes

JOBS_DIR.mkdir(parents=True, exist_ok=True)
os.chmod(JOBS_DIR, 0o700)

# In-memory registry only. Restarting the server invalidates all tokens.
_jobs: dict[str, dict] = {}

def new_job(credential_kind: str) -> dict:
    job_id = secrets.token_hex(16)
    file_token = secrets.token_urlsafe(32)
    job_dir = JOBS_DIR / job_id
    job_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(job_dir, 0o700)
    now = time.time()
    job = {
        "job_id": job_id,
        "file_token": file_token,
        "credential_kind": credential_kind,
        "status": "queued",
        "stage": "received",
        "progress": 0,
        "message": "已收到，正在解析 session…",
        "created_at": now,
        "expires_at": now + TTL_SECONDS,
        "subscription": None,
        "billing_platform": None,
        "invoices": [],
        "files": [],  # {name, kind, size, content_type}
        "error": None,  # {stage, code, message, hint, http_status, url, page_title}
        "log": [],  # stage transitions only, no credential data
    }
    _jobs[job_id] = job
    return job

def get_job(job_id: str) -> dict | None:
    job = _jobs.get(job_id)
    if job is None:
        return None
    if time.time() > job["expires_at"]:
        delete_job(job_id)
        return None
    return job

def job_dir(job_id: str) -> Path:
    return JOBS_DIR / job_id

def check_file_token(job: dict, token: str | None) -> bool:
    if not token:
        return False
    return hmac.compare_digest(job["file_token"], token)

def public_job(job: dict) -> dict:
    """What the frontend / API may return. Never includes file_token."""
    return {
        "job_id": job["job_id"],
        "status": job["status"],
        "stage": job["stage"],
        "progress": job["progress"],
        "message": job["message"],
        "created_at": job["created_at"],
        "expires_at": job["expires_at"],
        "subscription": job["subscription"],
        "billing_platform": job["billing_platform"],
        "invoices": job["invoices"],
        "files": job["files"],
        "error": job["error"],
        "log": job["log"],
    }

def update_job(job: dict, **fields):
    job.update(fields)
    if "stage" in fields:
        job["log"].append({
            "at": time.time(),
            "stage": fields["stage"],
            "message": fields.get("message", ""),
        })

def fail_job(job: dict, *, stage: str, code: str, message: str, hint: str = "",
             http_status: int | None = None, url: str | None = None,
             page_title: str | None = None):
    job["status"] = "failed"
    job["stage"] = stage
    job["progress"] = 100
    job["message"] = message
    job["error"] = {
        "stage": stage,
        "code": code,
        "message": message,
        "hint": hint,
        "http_status": http_status,
        "url": url,
        "page_title": page_title,
    }
    job["log"].append({"at": time.time(), "stage": stage, "message": message})

def save_file(job: dict, filename: str, data: bytes, kind: str, content_type: str) -> dict:
    # filename is always generated by us, never taken from user input.
    safe = Path(filename).name
    path = job_dir(job["job_id"]) / safe
    path.write_bytes(data)
    os.chmod(path, 0o600)
    entry = {"name": safe, "kind": kind, "size": len(data), "content_type": content_type}
    # Replace same-name entry if re-saved.
    job["files"] = [f for f in job["files"] if f["name"] != safe] + [entry]
    return entry

def delete_job(job_id: str):
    _jobs.pop(job_id, None)
    d = JOBS_DIR / job_id
    if d.exists():
        shutil.rmtree(d, ignore_errors=True)

def sweep_expired() -> int:
    now = time.time()
    expired = [jid for jid, j in list(_jobs.items()) if now > j["expires_at"]]
    for jid in expired:
        delete_job(jid)
    # Also remove orphan directories with no registry entry.
    if JOBS_DIR.exists():
        for d in JOBS_DIR.iterdir():
            if d.is_dir() and d.name not in _jobs:
                shutil.rmtree(d, ignore_errors=True)
    return len(expired)

def file_sha256(job_id: str, filename: str) -> str | None:
    p = job_dir(job_id) / Path(filename).name
    if not p.exists():
        return None
    return hashlib.sha256(p.read_bytes()).hexdigest()
